function mergeExpandedStages(
    base: LanguageCurriculumTree,
    expanded: readonly CurriculumStageGroup[],
): LanguageCurriculumTree {
    return {
        ...base,
        foundationStages: [
            ...base.foundationStages,
            ...expanded.filter((stage) => stage.zone === 'FOUNDATION'),
        ],
        dictionaryStages: [
            ...base.dictionaryStages,
            ...expanded.filter((stage) => stage.zone === 'DICTIONARY'),
        ],
        progressionStages: [
            ...base.progressionStages,
            ...expanded.filter((stage) => stage.zone === 'PROGRESSION'),
        ],
        literatureStages: [
            ...base.literatureStages,
            ...expanded.filter((stage) => stage.zone === 'LITERATURE'),
        ],
    };
}

